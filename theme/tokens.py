# سلّم الخطوط — Inter للاتيني، Cairo للعربي. الترتيب ده مقصود: Inter مفيهوش
# حروف عربية خالص، فالمتصفح بيقع تلقائيًا على Cairo لأي حرف عربي من غير ما
# نضطر نلف الاتنين في عناصر مختلفة أو نفحص اللغة في بايثون.
FONT_STACK = '"Inter", "Cairo", -apple-system, BlinkMacSystemFont, "Segoe UI", sans-serif'

MODES = {"dark": DARK, "light": LIGHT}


def css_vars(mode="dark", selector=":root"):
    """بتطلع بلوك CSS بكل التوكنز كـ custom properties.

    الخام بتاع البراند بيتطلع كمان (‎--cf-yellow‎، ‎--cf-ink‎ …) عشان اللوجو
    والحقل الأصفر — دول بس المسموح لهم يلمسوا الخام حسب الدليل.
    """
    pal = MODES[mode]
    rows = []
    for key, val in BRAND.items():
        rows.append(f"    --cf-{key.replace('_', '-')}: {val};")
    for key, val in pal.items():
        if key == "name":
            continue
        rows.append(f"    --cf-{key.replace('_', '-')}: {val};")
    for key, val in MATERIAL.items():
        rows.append(f"    --cf-{key.replace('_', '-')}: {val};")
    rows.append(f"    --cf-font: {FONT_STACK};")
    # السطوع بيتحرك مع الماوس؛ القيم الافتراضية دي بتخلي اللمعة واقفة على
    # الحرف العلوي لما مفيش pointer (موبايل/تابلت)
    rows.append("    --cf-sheen-x: 50%;")
    rows.append("    --cf-sheen-y: 0%;")
    rows.append("    --cf-sheen-a: 0;")
    return "%s {\n%s\n}" % (selector, "\n".join(rows))


# تجمّعات الضوء في الأرضية: (عرض, طول, س%, ص%, اللون, نهاية)
# س% مكتوبة بمنطق RTL (العربي هو الأساس) وبتتعكس للإنجليزي
_POOLS = [
    (1180, 780, 18, 10, "pool_indigo", 62),
    (940, 640, 86, 26, "pool_navy", 60),
    (820, 560, 74, 92, "bloom_gold", 66),
    (700, 480, 6, 84, "counter_teal", 62),
]


def ground_css(mode="dark", dir_="rtl"):
    """الميش جراديينت الثابت. راديال جراديينتس فوق اللون الأساسي، من غير
    أنيميشن (low motion) — الحركة بتيجي من إن المحتوى بيسكرول فوق أرضية
    واقفة، وده اللي بيخلي المادة تقرا كزجاج مش كشفافية.

    الأرضية بتتعكس مع اتجاه اللغة: الوهج الدهبي المفروض يقع في ناحية بداية
    القراءة، فلو مقلبناهاش الإنجليزي بيطلع والثقل البصري في الناحية الغلط.
    """
    p = MODES[mode]
    mirror = dir_ != "rtl"
    layers = []
    for w, h, x, y, key, stop in _POOLS:
        gx = (100 - x) if mirror else x
        layers.append(
            f"radial-gradient({w}px {h}px at {gx}% {y}%, {p[key]}, transparent {stop}%)"
        )
    layers.append(p["ground_base"])
    return ",".join(layers)
